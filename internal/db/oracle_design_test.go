// A column's NOT NULL follows its default and its identity, as Oracle's
// syntax has it; MODIFY states only what changed, a default removed as
// DEFAULT NULL; only a table is renamed.
func TestOracleDesignSQL(t *testing.T) {
	d := oracleDialect{}
	if got := columnSQL(d, ColumnDesign{Name: "id", Type: "NUMBER(19)", AutoIncrement: true}, false); got != `"id" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL` {
		t.Errorf("identity: %s", got)
	}
	if got := columnSQL(d, ColumnDesign{Name: "qty", Type: "NUMBER(10)", Default: "1"}, false); got != `"qty" NUMBER(10) DEFAULT 1 NOT NULL` {
		t.Errorf("default: %s", got)
	}
	if got := columnSQL(DialectOf(Postgres), ColumnDesign{Name: "qty", Type: "int", Default: "1"}, false); got != `"qty" int NOT NULL DEFAULT 1` {
		t.Errorf("PostgreSQL's order changed: %s", got)
	}
	r := oracleEngine{}
	tbl := TableDesign{Schema: "S", Name: "t"}
	for _, c := range []struct {
		was, now ColumnDesign
		want     []string
	}{
		{ColumnDesign{Name: "a", Type: "NUMBER(10)"}, ColumnDesign{Name: "a", Type: "NUMBER(19)"}, []string{`MODIFY ("a" NUMBER(19))`}},
		{ColumnDesign{Name: "a", Type: "NUMBER(10)", Default: "1"}, ColumnDesign{Name: "a", Type: "NUMBER(10)", Nullable: true},
			[]string{`MODIFY ("a" DEFAULT NULL NULL)`}},
		{ColumnDesign{Name: "a", Type: "VARCHAR2(5)", Nullable: true}, ColumnDesign{Name: "a", Type: "VARCHAR2(9)", Default: "'x'", Comment: "it's"},
			[]string{`MODIFY ("a" VARCHAR2(9) DEFAULT 'x' NOT NULL)`, `COMMENT ON COLUMN "S"."t"."a" IS 'it''s'`}},
	} {
		if got, err := r.ModifyColumnSQL(d, tbl, c.was, c.now); err != nil || !slices.Equal(got, c.want) {
			t.Errorf("%+v to %+v: %q %v", c.was, c.now, got, err)
		}
	}
	if _, err := r.ModifyColumnSQL(d, tbl, ColumnDesign{Name: "a", Type: "NUMBER"}, ColumnDesign{Name: "a", Type: "NUMBER", AutoIncrement: true}); err == nil {
		t.Error("identity added by MODIFY")
	}
	if got, err := r.RenameObjectSQL(Object{Schema: "S", Name: "t", Kind: KindTable}, "u"); err != nil || got != `ALTER TABLE "S"."t" RENAME TO "u"` {
		t.Errorf("rename: %q %v", got, err)
	}
	if _, err := r.RenameObjectSQL(Object{Schema: "S", Name: "v", Kind: KindView}, "w"); err == nil {
		t.Error("a view renamed by RENAME, which may rename another schema's")
	}
}

// A table of the designer's first column and every common type is made,
// numbers its rows itself, and reads back with its types; every DuckDB
// type a copy maps to Oracle makes a column, which maps back to the kind
// it came from.
func TestOracleDesignTypes(t *testing.T) {
	d := openOracle(t, oracleConfig)
	ctx := context.Background()
	r := oracleEngine{}
	drop := func() { d.SQL.ExecContext(ctx, `DROP TABLE IF EXISTS "DGOPHER"."it_types"`) }
	drop()
	t.Cleanup(drop)
	design := TableDesign{Schema: "DGOPHER", Name: "it_types", Columns: []ColumnDesign{r.FirstColumn()}}
	for i, typ := range r.CommonTypes() {
		design.Columns = append(design.Columns, ColumnDesign{Name: "c" + string(rune('a'+i)), Type: typ, Nullable: true})
	}
	ch, err := NewTableChange(d.Dialect, design)
	if err != nil {
		t.Fatal(err)
	}
	if ran, err := apply(t, d, ch); err != nil {
		t.Fatalf("%v:\n%s", err, strings.Join(ran, "\n"))
	}
	mustExec(t, d, `INSERT INTO "DGOPHER"."it_types" ("ca") VALUES (7)`, `INSERT INTO "DGOPHER"."it_types" ("ca") VALUES (8)`)
	var ids string
	if err := d.SQL.QueryRowContext(ctx, `SELECT LISTAGG("id", ',') WITHIN GROUP (ORDER BY "id") FROM "DGOPHER"."it_types"`).Scan(&ids); err != nil || ids != "1,2" {
		t.Fatalf("identity numbers %q: %v", ids, err)
	}
	got, err := ReadTableDesign(ctx, d, Object{Schema: "DGOPHER", Name: "it_types", Kind: KindTable})
	if err != nil {
		t.Fatal(err)
	}
	if c := got.Columns[0]; !c.PrimaryKey || !c.AutoIncrement || c.Type != "NUMBER(19)" {
		t.Fatalf("first column %+v", c)
	}
	for i, typ := range r.CommonTypes() {
		k1, _, _ := r.TypeKindOf(typ)
		k2, _, _ := r.TypeKindOf(got.Columns[i+1].Type)
		if k1 != k2 {
			t.Errorf("%s reads back as %s, of kind %s, not %s", typ, got.Columns[i+1].Type, k2, k1)
		}
	}

	duck := []string{"BOOLEAN", "TINYINT", "SMALLINT", "INTEGER", "BIGINT", "UBIGINT", "HUGEINT", "FLOAT", "DOUBLE", "DECIMAL(12,3)", "DATE",
		"TIMESTAMP", "TIMESTAMP_NS", "TIMESTAMP WITH TIME ZONE", "UUID", "BLOB", "VARCHAR", "INTERVAL"}
	design = TableDesign{Schema: "DGOPHER", Name: "it_types"}
	for i, typ := range duck {
		design.Columns = append(design.Columns, ColumnDesign{Name: "c" + string(rune('a'+i)), Type: r.ColumnTypeFor(typ), Nullable: true})
	}
	drop()
	if ch, err = NewTableChange(d.Dialect, design); err != nil {
		t.Fatal(err)
	}
	if ran, err := apply(t, d, ch); err != nil {
		t.Fatalf("%v:\n%s", err, strings.Join(ran, "\n"))
	}
	cols, err := d.Dialect.Columns(ctx, d.SQL, "DGOPHER", "it_types")
	if err != nil || len(cols) != len(duck) {
		t.Fatalf("columns %+v: %v", cols, err)
	}
	back := map[string]string{"BOOLEAN": "DECIMAL(1,0)", "TINYINT": "BIGINT", "SMALLINT": "BIGINT", "INTEGER": "BIGINT", "BIGINT": "BIGINT",
		"UBIGINT": "DECIMAL(38,0)", "HUGEINT": "DECIMAL(38,0)", "FLOAT": "FLOAT", "DOUBLE": "DOUBLE", "DECIMAL(12,3)": "DECIMAL(12,3)",
		"DATE": "TIMESTAMP", "TIMESTAMP": "TIMESTAMP", "TIMESTAMP_NS": "TIMESTAMP", "TIMESTAMP WITH TIME ZONE": "TIMESTAMPTZ",
		"UUID": "VARCHAR", "BLOB": "BLOB", "VARCHAR": "VARCHAR", "INTERVAL": "VARCHAR"}
	for i, typ := range duck {
		if got := r.CanonicalType(cols[i].Type); got != back[typ] {
			t.Errorf("%s made %s, which maps back to %s, want %s", typ, cols[i].Type, got, back[typ])
		}
	}
}
