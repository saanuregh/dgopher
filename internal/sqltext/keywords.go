var keywordSets = map[Dialect]map[string]bool{}

func init() {
	extra := map[Dialect]string{Generic: "", Postgres: postgresKeywords, MySQL: mysqlKeywords, ClickHouse: clickhouseKeywords, SQLite: "GLOB PRAGMA",
		TSQL: tsqlReservedKeywords + " " + tsqlKeywords, Oracle: oracleReservedKeywords + " " + oracleKeywords}
	for d, words := range extra {
		set := map[string]bool{}
		for _, w := range strings.Fields(standardKeywords + " " + words) {
			set[w] = true
		}
		keywordSets[d] = set
	}
}

func keywordSet(d Dialect) map[string]bool {
	if s, ok := keywordSets[d]; ok {
		return s
	}
	return keywordSets[Generic]
}

// Keywords returns the sorted upper-case keyword list for the dialect.
func Keywords(d Dialect) []string {
	set := keywordSet(d)
	out := make([]string, 0, len(set))
	for w := range set {
		out = append(out, w)
	}
	sort.Strings(out)
	return out
}
