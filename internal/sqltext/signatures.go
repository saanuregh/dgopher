package sqltext

// Signature is a function's calling form, as a hover card shows it.
type Signature struct {
	Name        string
	Args        string // as written in a call's parentheses, e.g. "v numeric, s integer"
	Result      string // the type returned, "" when unknown or a procedure
	Description string
	Aggregate   bool
}

// BuiltinSignatures is the dialect's own table of common built-in
// functions, for engines whose servers keep no structured catalog of
// them; nil for the others.
func BuiltinSignatures(d Dialect) []Signature {
	switch d {
	case SQLite:
		return sqliteSignatures
	case MySQL:
		return mysqlSignatures
	}
	return nil
}

func fn(name, args, result, description string) Signature {
	return Signature{Name: name, Args: args, Result: result, Description: description}
}

func agg(name, args, result, description string) Signature {
	return Signature{Name: name, Args: args, Result: result, Description: description, Aggregate: true}
}

