// oracleServers is the Oracle test server, as SYSTEM, when it runs (the
// enterprise profile): a schema is a user, which owns no password.
func oracleServers() []server {
	c, err := net.DialTimeout("tcp", "127.0.0.1:11521", time.Second)
	if err != nil {
		return nil
	}
	c.Close()
	return []server{{
		cfg:          db.Config{Name: "oracle", Engine: db.Oracle, Host: "127.0.0.1", Port: 11521, User: "system", Password: "dgopher", Database: "FREEPDB1"},
		createSchema: func(s string) string { return `CREATE USER "` + s + `" NO AUTHENTICATION QUOTA UNLIMITED ON USERS` },
		dropSchema:   func(s string) string { return `DROP USER IF EXISTS "` + s + `" CASCADE` },
	}}
}

// A model built from Oracle, its names as written, makes its schema again
// in another schema, alike, numbering its rows by identity; a migration
// then makes the copy like the model changed; and the model's script for
// each other engine runs there.
func TestIntegrationOracleModels(t *testing.T) {
	testutil.Integration(t)
	srvs := oracleServers()
	if len(srvs) == 0 {
		t.Skip("Oracle is not running: start it with docker compose --profile enterprise up -d --wait oracle")
	}
	srv := srvs[0]
	ctx := context.Background()
	d, err := db.Open(ctx, srv.cfg, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer d.Close()
	exec := func(stmts ...string) {
		t.Helper()
		for _, s := range stmts {
			if _, err := d.SQL.ExecContext(ctx, s); err != nil {
				t.Fatalf("%s: %v", s, err)
			}
		}
	}
	for _, s := range []string{"it_model_a", "it_model_b"} {
		exec(srv.dropSchema(s), srv.createSchema(s))
		defer d.SQL.ExecContext(ctx, srv.dropSchema(s))
	}
	exec(`CREATE TABLE "it_model_a"."customers" ("id" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "email" VARCHAR2(100) NOT NULL,
			"name" VARCHAR2(50) DEFAULT 'none', CONSTRAINT "customers_email" UNIQUE ("email"))`,
		`CREATE TABLE "it_model_a"."orders" ("id" NUMBER(10) PRIMARY KEY, "customer_id" NUMBER(10), "total" NUMBER(10,2) NOT NULL,
			CONSTRAINT "orders_customer_fk" FOREIGN KEY ("customer_id") REFERENCES "it_model_a"."customers" ("id") ON DELETE CASCADE,
			CONSTRAINT "orders_total" CHECK ("total" >= 0))`,
		`CREATE INDEX "it_model_a"."orders_total_ix" ON "it_model_a"."orders" ("total")`,
		`CREATE TABLE "it_model_a"."a" ("id" NUMBER(10) PRIMARY KEY, "b_id" NUMBER(10))`,
		`CREATE TABLE "it_model_a"."b" ("id" NUMBER(10) PRIMARY KEY, "a_id" NUMBER(10), CONSTRAINT "b_a" FOREIGN KEY ("a_id") REFERENCES "it_model_a"."a" ("id"))`,
		`ALTER TABLE "it_model_a"."a" ADD CONSTRAINT "a_b" FOREIGN KEY ("b_id") REFERENCES "it_model_a"."b" ("id")`)
	read := func(schema string) *Model {
		t.Helper()
		tables, notes, err := Build(ctx, d, schema, nil, nil)
		if err != nil || len(notes) > 0 {
			t.Fatal(err, notes)
		}
		return &Model{Name: "shop", Engine: srv.cfg.Engine, Tables: tables}
	}
	m := read("it_model_a")
	o, ok := m.Table("it_model_a", "orders")
	if !ok || len(o.Checks) != 1 || !slices.ContainsFunc(o.ForeignKeys, func(fk db.ForeignKeyDesign) bool { return fk.OnDelete == "CASCADE" }) {
		t.Fatalf("orders %+v", o)
	}
	ch, notes := Script(m, srv.cfg.Engine, "it_model_b")
	if len(notes) > 0 {
		t.Fatalf("notes %q", notes)
	}
	apply(t, d, ch)
	unchanged(t, m, read("it_model_b"))
	exec(`INSERT INTO "it_model_b"."customers" ("email") VALUES ('ada@example.com')`)

	i := slices.IndexFunc(m.Tables, func(t db.TableDesign) bool { return t.Name == "orders" })
	m.Tables[i].Columns = append(m.Tables[i].Columns, db.ColumnDesign{Name: "note", Type: "VARCHAR2(20)", Nullable: true})
	m.Tables = append(m.Tables, db.TableDesign{Schema: "it_model_a", Name: "items", Columns: []db.ColumnDesign{
		{Name: "id", Type: "NUMBER(10)", PrimaryKey: true}, {Name: "order_id", Type: "NUMBER(10)", Nullable: true}},
		ForeignKeys: []db.ForeignKeyDesign{{Name: "items_order", Columns: []string{"order_id"}, RefSchema: "it_model_a", RefTable: "orders", RefColumns: []string{"id"}}}})
	ch, notes, err = Migration(m, read("it_model_b"), "it_model_b", false)
	if err != nil || len(notes) > 0 {
		t.Fatal(err, notes)
	}
	apply(t, d, ch)
	unchanged(t, m, read("it_model_b"))
	ch, notes, err = Migration(read("it_model_a"), read("it_model_b"), "it_model_b", true)
	if err != nil || len(notes) > 0 {
		t.Fatal(err, notes)
	}
	apply(t, d, ch)
	unchanged(t, read("it_model_a"), read("it_model_b"))

	for _, other := range servers() {
		od, err := db.Open(ctx, other.cfg, nil)
		if err != nil {
			t.Fatal(err)
		}
		defer od.Close()
		for _, s := range []string{other.dropSchema("it_model_c"), other.createSchema("it_model_c")} {
			if _, err := od.SQL.ExecContext(ctx, s); err != nil {
				t.Fatal(s, err)
			}
		}
		ch, _ := Script(m, other.cfg.Engine, "it_model_c")
		apply(t, od, ch)
		od.SQL.ExecContext(ctx, other.dropSchema("it_model_c"))
	}
}
